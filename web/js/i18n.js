let lang = 'en';
export function setLang(l) { lang = STR[l] ? l : 'en'; document.documentElement.lang = lang; applyI18n(); }
export function getLang() { return lang; }
export function t(key) { return (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key; }
/** Väljer rätt språk ur ett objekt {sv:'…', en:'…'} eller returnerar strängen. */
export function tr(v) { return v && typeof v === 'object' ? (v[lang] ?? v.en ?? v.sv ?? '') : (v ?? ''); }
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
}
